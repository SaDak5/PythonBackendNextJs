import random

def get_random_response(responses):
    return random.choice(responses)

def find_faq(query):
    
    results = []
    query_lower = query.lower()
    
    for category in faq_questions:
        for faq in category["questions"]:
           
            if "keywords" in faq:
                keyword_matches = sum(1 for keyword in faq["keywords"] if keyword.lower() in query_lower)
                if keyword_matches > 0:
                    faq["match_score"] = keyword_matches * 10
                    results.append(faq)
                    continue
            
          
            if query_lower in faq["question"].lower():
                faq["match_score"] = 5
                results.append(faq)
                continue
            
      
            if any(query_lower in tag.lower() for tag in faq["tags"]):
                faq["match_score"] = 3
                results.append(faq)
                continue
            
        
            for response in faq["responses"]:
                if query_lower in response.lower():
                    faq["match_score"] = 1
                    results.append(faq)
                    break
    
  
    results.sort(key=lambda x: x.get("match_score", 0), reverse=True)
    
   
    for result in results:
        if "match_score" in result:
            del result["match_score"]
    
    return results

def get_suggestions(query):
    suggestions = []
    query_lower = query.lower()
    
    for category in faq_questions:
        for faq in category["questions"]:
            # Vérifier les keywords en premier
            if "keywords" in faq:
                has_keyword_match = any(
                    keyword.lower() in query_lower or query_lower in keyword.lower()
                    for keyword in faq["keywords"]
                )
                if has_keyword_match:
                    suggestions.append(faq["question"])
                    if len(suggestions) >= 5:
                        return suggestions
            
            has_matching_tag = any(
                tag.lower() in query_lower or query_lower in tag.lower()
                for tag in faq["tags"]
            )
         
            question_words = set(faq["question"].lower().split())
            query_words = set(query_lower.split())
            has_matching_words = len(question_words.intersection(query_words)) > 0
            
            if has_matching_tag or has_matching_words:
                suggestions.append(faq["question"])
            
            if len(suggestions) >= 5:
                break
        if len(suggestions) >= 5:
            break
    
    return suggestions